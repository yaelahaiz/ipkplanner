export type Grade = "A" | "A-" | "B+" | "B" | "B-" | "C+" | "C" | "C-" | "D" | "E";
export type Course = { id: string; name: string; sks: number | ""; grade: Grade };
export type Semester = { id: number; courses: Course[] };
export type AcademicData = { targetSks: number; semesters: Semester[] };
export type UserProfile = { nim: string; name: string; role: "student" | "admin"; active: boolean };
export type GraduateProfile = { code: string; title: string; description: string };
export type Cpl = { code: string; description: string; keyword: string; profileCodes: string[] };
export type CurriculumCourse = { name: string; sks: number; semester: number | null; cplCodes: string[] };
export type Cpmk = { code: string; description: string; course: string; cplCode: string };
export type Curriculum = { programCode: string; programName: string; target: number; profiles: GraduateProfile[]; cpls: Cpl[]; courses: CurriculumCourse[]; cpmks: Cpmk[]; source: string; updatedAt?: unknown };
export type CplAssessment = { id: string; course: string; cpmkCode: string; cplCode: string; score: number; cohort: string; semester: number };
